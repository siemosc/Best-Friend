"""Structured output генерации карточки сущности."""

from pydantic import BaseModel, Field


class EntityCardOutput(BaseModel):
    """Карточка сущности: один плотный документ «всё важное про X»."""

    content: str = Field(
        description=(
            "Связный плотный текст карточки: кто/что это, текущее состояние, "
            "ключевые факты, решения и события с датами. Конкретные имена и "
            "значения прямо в тексте. Язык — язык заметок."
        )
    )
