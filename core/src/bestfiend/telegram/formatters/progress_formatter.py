"""Форматирование прогресс-сообщений для telegram-канала.

Текст прогресса приходит от ядра готовым (`ProgressStep.text`); формат-модуль
добавляет канал-специфичную декорацию — префикс `⏳` — и собирает накопленные
строки в одно сообщение для редактирования.
"""

_PREFIX = "⏳"


def format_progress(texts: list[str]) -> str:
    """Склеивает накопленные шаги в многострочное сообщение."""
    return "\n".join(_format_step(t) for t in texts)


def _format_step(text: str) -> str:
    """Декорирует один шаг прогресса префиксом канала."""
    return f"{_PREFIX} {text}"
